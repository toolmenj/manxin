import { useEffect, useState } from 'react';
import { api } from '../api/client.ts';

function useContact(): string | null {
  const [c, setC] = useState<string | null>(null);
  useEffect(() => {
    api
      .publicConfig()
      .then((r) => setC(r.contactEmail))
      .catch(() => setC(null));
  }, []);
  return c;
}

const UPDATED = '民國 115 年 11 月 12 日';

function Contact() {
  const c = useContact();
  return c ? (
    <a href={`mailto:${c}`}>{c}</a>
  ) : (
    <span>網站上公布的聯絡信箱</span>
  );
}

